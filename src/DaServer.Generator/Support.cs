using System.Linq;
using Microsoft.CodeAnalysis;

namespace DaServer.Generator;

/// <summary>Shared helpers of the DaServer generators.</summary>
internal static class Support
{
    public const string Header = "// <auto-generated/>\n#nullable enable\n#pragma warning disable CS1591\n";

    /// <summary>Fully qualified, with nullable annotations (for emitted code).</summary>
    public static readonly SymbolDisplayFormat Fqn = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    /// <summary>FNV-1a 32, identical to DaServer.Rpc.RpcIds.Fnv1a (0 is reserved).</summary>
    public static uint Fnv1a(string text)
    {
        uint hash = 2166136261;
        foreach (char c in text)
        {
            hash = (hash ^ (byte)c) * 16777619;
            hash = (hash ^ (byte)(c >> 8)) * 16777619;
        }

        return hash == 0 ? 1u : hash;
    }

    public static bool Implements(ITypeSymbol type, string interfaceName) =>
        type.AllInterfaces.Any(i => i.ToDisplayString() == interfaceName);

    public static bool DerivesFrom(ITypeSymbol type, string baseName)
    {
        for (var b = type.BaseType; b != null; b = b.BaseType)
            if (b.ToDisplayString() == baseName) return true;
        return false;
    }

    /// <summary>"IPlayerClient" -> "PlayerClient".</summary>
    public static string StripInterfacePrefix(string name) =>
        name.Length > 1 && name[0] == 'I' && char.IsUpper(name[1]) ? name.Substring(1) : name;

    /// <summary>A valid C# identifier derived from <paramref name="text"/> (e.g. an assembly name).</summary>
    public static string Identifier(string text)
    {
        var chars = text.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray();
        return chars.Length > 0 && char.IsDigit(chars[0]) ? "_" + new string(chars) : new string(chars);
    }

    public static string HintName(string fullName) =>
        fullName.Replace("global::", "").Replace('<', '_').Replace('>', '_').Replace(',', '_').Replace(' ', '_');
}

/// <summary>Location data that survives incremental caching (no syntax trees retained).</summary>
internal sealed record LocationInfo(string Path, Microsoft.CodeAnalysis.Text.TextSpan Span,
    Microsoft.CodeAnalysis.Text.LinePositionSpan Lines)
{
    public Location ToLocation() => Location.Create(Path, Span, Lines);

    public static LocationInfo? From(Location? location) => location?.SourceTree is null
        ? null
        : new LocationInfo(location.SourceTree.FilePath, location.SourceSpan, location.GetLineSpan().Span);
}

internal sealed record DiagnosticInfo(DiagnosticDescriptor Descriptor, LocationInfo? Location, string Arg0, string Arg1)
{
    public Diagnostic ToDiagnostic() => Diagnostic.Create(Descriptor, Location?.ToLocation(), Arg0, Arg1);
}

internal static class Rules
{
    private const string Category = "DaServer";

    public static readonly DiagnosticDescriptor BadReturnType = new("DAS001", "Unsupported RPC return type",
        "Method '{0}' of RPC contract '{1}' must return ValueTask, ValueTask<T> or void (one-way); Task is not allowed (it allocates)",
        Category, DiagnosticSeverity.Error, true);

    public static readonly DiagnosticDescriptor BadParameter = new("DAS002", "Unsupported RPC parameter",
        "Parameter '{0}' of RPC method '{1}' must be passed by value (no ref/out/in/params)", Category,
        DiagnosticSeverity.Error, true);

    public static readonly DiagnosticDescriptor GenericMember = new("DAS003", "Generic RPC member",
        "RPC contract '{0}' and its methods cannot be generic", Category, DiagnosticSeverity.Error, true);

    public static readonly DiagnosticDescriptor CallbackMustBeVoid = new("DAS004", "Client callbacks are one-way",
        "Method '{0}' of client callback '{1}' must return void", Category, DiagnosticSeverity.Error, true);

    public static readonly DiagnosticDescriptor IdCollision = new("DAS005", "RPC method id collision",
        "Methods '{0}' and '{1}' hash to the same wire id; add [RpcId] to one of them", Category,
        DiagnosticSeverity.Error, true);

    public static readonly DiagnosticDescriptor ActorBase = new("DAS006", "Actor implementation must derive from Actor",
        "'{0}' implements actor contract '{1}' and must derive from DaServer.Runtime.Actor", Category,
        DiagnosticSeverity.Error, true);

    public static readonly DiagnosticDescriptor NoDefaultConstructor = new("DAS007", "Missing parameterless constructor",
        "'{0}' must have a public parameterless constructor (the runtime creates one instance per shard/activation)",
        Category, DiagnosticSeverity.Error, true);

    public static readonly DiagnosticDescriptor NoMethods = new("DAS008", "Properties and events are not supported",
        "RPC contract '{0}' may only declare methods (member '{1}')", Category, DiagnosticSeverity.Error, true);
}
