namespace DaServer.Generator;

/// <summary>Shared helpers of the DaServer generators and analyzer.</summary>
internal static class Support
{
    public const string Header = "// <auto-generated/>\n#nullable enable\n#pragma warning disable CS1591\n";

    public const string HandleAttribute = "DaServer.Rpc.HandleAttribute";
    public const string MessageAttribute = "DaServer.Rpc.MessageAttribute";
    public const string ClusterClientType = "DaServer.Client.ClusterClient";

    /// <summary>DaServer.Rpc.Flow values.</summary>
    public const int FlowFromClient = 1, FlowToClient = 2;
    public const string WireIdAttribute = "DaServer.Rpc.WireIdAttribute";
    public const string RequestInterface = "DaServer.Rpc.IRequest<TReply>";
    public const string NinoTypeAttribute = "Nino.Core.NinoTypeAttribute";
    public const string ActorBase = "DaServer.Runtime.Actor";
    public const string ServiceBase = "DaServer.Runtime.Service";
    public const string EcsSystem = "EasyEcs.EcsSystem";

    /// <summary>Fully qualified, with nullable annotations (for emitted code).</summary>
    public static readonly SymbolDisplayFormat Fqn = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    /// <summary>FNV-1a 32, identical to DaServer.Rpc.RpcIds.Fnv1a (0 is reserved).</summary>
    public static uint Fnv1a(string text)
    {
        uint hash = 2166136261;
        foreach (char c in text)
        {
            hash = (hash ^ (byte)c) * 16777619;
            hash = (hash ^ (byte)(c >> 8)) * 16777619;
        }

        return hash == 0 ? 1u : hash;
    }

    public static bool HasAttribute(ISymbol symbol, string attributeName) => GetAttribute(symbol, attributeName) != null;

    public static AttributeData? GetAttribute(ISymbol symbol, string attributeName) =>
        symbol.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == attributeName);

    public static bool DerivesFrom(ITypeSymbol type, string baseName)
    {
        for (var b = type.BaseType; b != null; b = b.BaseType)
            if (b.ToDisplayString() == baseName || b.ConstructedFrom.ToDisplayString() == baseName) return true;
        return false;
    }

    /// <summary>A valid C# identifier derived from <paramref name="text"/> (e.g. an assembly name).</summary>
    public static string Identifier(string text)
    {
        var chars = text.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray();
        return chars.Length > 0 && char.IsDigit(chars[0]) ? "_" + new string(chars) : new string(chars);
    }

    public static string HintName(string fullName) =>
        fullName.Replace("global::", "").Replace('<', '_').Replace('>', '_').Replace(',', '_').Replace(' ', '_');
}

/// <summary>Receives problems found while reading symbols; null for the generator, which only needs validity.</summary>
internal delegate void Report(DiagnosticDescriptor descriptor, Location? location, params object[] args);
