namespace DaServer.Generator;

/// <summary>Shared helpers of the DaServer generators and analyzer.</summary>
internal static class Support
{
    public const string Header = "// <auto-generated/>\n#nullable enable\n#pragma warning disable CS1591\n";

    /// <summary>
    /// Whether a compilation hosts the server runtime: its generated code is C# 14 (built by the .NET 11 SDK). Shared and
    /// client assemblies get C# 9 code, which Unity's compiler builds.
    /// </summary>
    public static bool IsServer(Compilation compilation)
    {
        foreach (var assembly in compilation.ReferencedAssemblyNames)
            if (assembly.Name == "DaServer") return true;
        return false;
    }

    /// <summary>Open <paramref name="ns"/> (a file-scoped one on the server, a block in C# 9 code); returns its closing text.</summary>
    public static string OpenNamespace(System.Text.StringBuilder sb, string ns, bool server)
    {
        if (ns.Length == 0) return "";
        if (server)
        {
            sb.Append("namespace ").Append(ns).Append(";\n\n");
            return "";
        }

        sb.Append("namespace ").Append(ns).Append("\n{\n");
        return "}\n";
    }

    public const string HandleAttribute = "DaServer.HandleAttribute";
    public const string MessageAttribute = "DaServer.MessageAttribute";
    public const string PersistAttribute = "DaServer.PersistAttribute";
    public const string HandoffAttribute = "DaServer.HandoffAttribute";
    public const string ClusterClientType = "DaServer.Client.ClusterClient";
    public const string ActorId = "DaServer.IActorId";
    public const string Placed = "DaServer.IPlaced";

    /// <summary>Address types of client connections: messages sent to them reach clients (<c>[ToClient]</c>).</summary>
    public static readonly string[] ClientAddresses = ["DaServer.ClientSession", "DaServer.Origin", "DaServer.ClientGroup"];

    public const string FromClientAttribute = "DaServer.FromClientAttribute";
    public const string ToClientAttribute = "DaServer.ToClientAttribute";

    /// <summary>Who a message travels between, besides servers (bits of <see cref="Shapes.FlowOf"/>).</summary>
    public const int FlowFromClient = 1, FlowToClient = 2;
    public const string NinoFormerNameAttribute = "Nino.Core.NinoFormerNameAttribute";
    public const string RequestInterface = "DaServer.IRequest`1";
    public const string NinoTypeAttribute = "Nino.Core.NinoTypeAttribute";
    public const string ActorBase = "DaServer.Runtime.Actor";
    public const string ServiceBase = "DaServer.Runtime.Service";
    public const string EcsSystem = "EasyEcs.EcsSystem";

    /// <summary>Fully qualified, with nullable annotations (for emitted code).</summary>
    public static readonly SymbolDisplayFormat Fqn = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    /// <summary>FNV-1a 32 over UTF-16 code units, identical to Nino's type ids (0 is reserved).</summary>
    public static uint Fnv1a(string text)
    {
        uint hash = 2166136261;
        foreach (char c in text)
        {
            hash = (hash ^ (byte)c) * 16777619;
            hash = (hash ^ (byte)(c >> 8)) * 16777619;
        }

        return hash == 0 ? 1u : hash;
    }

    public static bool HasAttribute(ISymbol symbol, string attributeName) => GetAttribute(symbol, attributeName) != null;

    public static AttributeData? GetAttribute(ISymbol symbol, string attributeName)
    {
        foreach (var attribute in symbol.GetAttributes())
            if (Is(attribute.AttributeClass, attributeName)) return attribute;
        return null;
    }

    public static bool DerivesFrom(ITypeSymbol type, string baseName)
    {
        for (var b = type.BaseType; b != null; b = b.BaseType)
            if (Is(b, baseName)) return true;
        return false;
    }

    public static bool Implements(ITypeSymbol type, string interfaceName)
    {
        foreach (var i in type.AllInterfaces)
            if (Is(i, interfaceName)) return true;
        return false;
    }

    /// <summary>
    /// Whether <paramref name="type"/> (its definition, for constructed generics) is the top-level type
    /// <paramref name="fullName"/> (metadata name: <c>Ns.Type</c>, generics with their arity, <c>DaServer.IRequest`1</c>).
    /// Compares name segments in place: symbol checks run for every type and call site of a compilation, so they
    /// allocate nothing (unlike comparing display strings).
    /// </summary>
    public static bool Is(ITypeSymbol? type, string fullName)
    {
        if (type == null || type.ContainingType != null) return false;
        int end = fullName.Length;
        if (!TrimSegment(fullName, ref end, type.OriginalDefinition.MetadataName)) return false;
        for (var ns = type.ContainingNamespace; ns is { IsGlobalNamespace: false }; ns = ns.ContainingNamespace)
            if (end == 0 || !TrimSegment(fullName, ref end, ns.Name)) return false;
        return end == 0;
    }

    /// <summary>Whether <paramref name="text"/> ends (before <paramref name="end"/>) with "." + segment or is it; moves end before it.</summary>
    private static bool TrimSegment(string text, ref int end, string segment)
    {
        int start = end - segment.Length;
        if (start < 0 || string.CompareOrdinal(text, start, segment, 0, segment.Length) != 0) return false;
        if (start == 0)
        {
            end = 0;
            return true;
        }

        if (text[start - 1] != '.') return false;
        end = start - 1;
        return true;
    }

    /// <summary>Whether <paramref name="type"/> is declared in namespace System or below it.</summary>
    public static bool InSystemNamespace(ITypeSymbol type)
    {
        var ns = type.ContainingNamespace;
        if (ns == null || ns.IsGlobalNamespace) return false;
        while (ns.ContainingNamespace is { IsGlobalNamespace: false } outer) ns = outer;
        return ns.Name == "System";
    }

    /// <summary>A valid C# identifier derived from <paramref name="text"/> (e.g. an assembly name).</summary>
    public static string Identifier(string text)
    {
        var chars = text.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray();
        return chars.Length > 0 && char.IsDigit(chars[0]) ? "_" + new string(chars) : new string(chars);
    }

    public static string HintName(string fullName) =>
        fullName.Replace("global::", "").Replace('<', '_').Replace('>', '_').Replace(',', '_').Replace(' ', '_');
}

/// <summary>Receives problems found while reading symbols; null for the generator, which only needs validity.</summary>
internal delegate void Report(DiagnosticDescriptor descriptor, Location? location, params object[] args);
