namespace DaServer.Generator;

/// <summary>
/// With <c>-p:UpdateWireManifest=true</c> (or <c>force</c>) writes the assembly's wire manifest (ADR-076) as the
/// comment of <c>DaServer.WireManifest.g.cs</c>, which the build copies to <c>wire.manifest</c>. It reads every type of
/// the compilation (Nino also serializes types that only inherit [NinoType]), so it runs only when asked: an ordinary
/// build emits nothing and costs nothing.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class WireManifestGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var updating = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
            options.GlobalOptions.TryGetValue("build_property.UpdateWireManifest", out var value) &&
            (string.Equals(value, "true", StringComparison.OrdinalIgnoreCase) || string.Equals(value, "force", StringComparison.OrdinalIgnoreCase)));
        var manifest = context.CompilationProvider.Combine(updating)
            .Select(static (pair, ct) => pair.Right ? Manifest(pair.Left, ct) : "")
            .WithTrackingName("WireManifest");

        context.RegisterSourceOutput(manifest, static (spc, text) =>
        {
            if (text.Length > 0) spc.AddSource("DaServer.WireManifest.g.cs", "// <auto-generated/>\n/*\n" + text + "*/\n");
        });
    }

    private static string Manifest(Compilation compilation, CancellationToken ct)
    {
        var types = WireManifest.All(compilation, ct);
        return types.Count == 0 ? "" : WireManifest.Format(types.Select(t => t.Type).ToList());
    }
}
